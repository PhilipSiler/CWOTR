#!/usr/bin/env python3
"""Generate src/data.h + src/data.c (map, cards, combat cards) from war-of-the-ring/assets JSON."""
import json, re, unicodedata, os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
A = os.path.join(ROOT, '..', 'war-of-the-ring', 'assets')
def san(s):
    s = unicodedata.normalize('NFKD', s).encode('ascii', 'ignore').decode()
    s = s.replace("'", "")
    return re.sub(r'[^A-Za-z0-9]+', '_', s).strip('_').upper()
m = json.load(open(os.path.join(A, 'map.json')))
cards = json.load(open(os.path.join(A, 'event-cards.json')))['cards']
regs = sorted(m['regions'].keys())
NAT = {'dwarves':'DWARVES','elves':'ELVES','gondor':'GONDOR','north':'NORTH','rohan':'ROHAN',
       'isengard':'ISENGARD','sauron':'SAURON','southrons':'SOUTHRON',None:'NO_NATION'}
SET = {None:'S_NONE','Town':'S_TOWN','City':'S_CITY','Stronghold':'S_STRONGHOLD','Fortification':'S_FORT'}
COAST = set("north-ered-luin south-ered-luin forlindon harlindon grey-havens minhiriath enedwaith druwaith-iaur andrast anfalas dol-amroth lamedon pelargir west-harondor umbar near-harad far-harad".split())
# symmetric adjacency check
for r in regs:
    for a in m['regions'][r]['adjacency']:
        assert r in m['regions'][a]['adjacency'], (r, a)
h = ["/* GENERATED by tools/gen_data.py -- do not edit */", "#ifndef WOTR_DATA_H", "#define WOTR_DATA_H", "#define NREG %d" % len(regs), "enum {"]
h += ["  R_%s = %d," % (san(r), i) for i, r in enumerate(regs)]
h += ["};", "enum {"]
h += ["  CARD_%s = %d," % (san(c['name']), i) for i, c in enumerate(cards)]
h += ["  NCARD = %d" % len(cards), "};"]
titles = []
for c in cards:
    t = c['combat']['title']
    if t not in titles: titles.append(t)
h += ["enum {"] + ["  CC_%s = %d," % (san(t), i) for i, t in enumerate(titles)] + ["  NCC = %d" % len(titles), "};", "#endif"]
open(os.path.join(ROOT, 'src', 'data.h'), 'w').write('\n'.join(h) + '\n')
c_ = ['/* GENERATED by tools/gen_data.py -- do not edit */', '#include "wotr.h"', 'const RegionInfo REGION[NREG] = {']
for r in regs:
    v = m['regions'][r]
    nat = NAT[v.get('nation')]
    su = v.get('setup') or {}
    sn = NAT[v.get('setupNation') or v.get('nation')] if su else 'NO_NATION'
    adj = [regs.index(a) for a in v['adjacency']]
    c_.append('  {"%s", %s, %s, %d, %d, {%s}, %s, %d, %d, %d, %d},' % (
        v.get('name', r), nat, SET[v.get('settlement')], 1 if r in COAST else 0, len(adj), ','.join(map(str, adj)),
        sn, su.get('regular', 0), su.get('elite', 0), su.get('leader', 0), su.get('nazgul', 0)))
c_.append('};')
TYPE = {'character':'F_CHAR','army':'F_ARMY','muster':'F_MUSTER'}
c_.append('const CardInfo CARD[NCARD] = {')
for c in cards:
    table = 1 if (c.get('precondition') or '').startswith('Play on the table') else 0
    c_.append('  {"%s", %s, CC_%s, %d},' % (c['name'].replace('"', '\\"'), TYPE[c['playableVia']], san(c['combat']['title']), table))
c_.append('};')
c_.append('const char *const CC_NAME[NCC] = {' + ', '.join('"%s"' % unicodedata.normalize('NFKD', t).encode('ascii','ignore').decode() for t in titles) + '};')
open(os.path.join(ROOT, 'src', 'data.c'), 'w').write('\n'.join(c_) + '\n')
print(len(regs), 'regions', len(cards), 'cards', len(titles), 'combat titles')
